import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {expect} from '@playwright/test';
import {meetingHarness, count, openPanel, panel, stats} from './helpers/live-meeting.mjs';

// Real local SFU/data channels/native tab capture. Account identities are fixtures;
// no real account, recording, transcript or production database is used.
const h = await meetingHarness({frontendBuild: process.env.TALK_TEST_FRONTEND_BUILD, lowResourceMedia: true});
const report = {passed: false, realLocalLiveKit: true, realNativeScreenCapture: false, physicalDevices: false};
let step = 'connect two local browsers';
let debugPage;
try {
  step='create host fixture';
  const host = await h.member('ReferenceHost'), guest = await h.member('ReferenceGuest');
  const a = host.page, b = guest.page;
  debugPage=a;
  await a.setViewportSize({width:1408,height:768});
  await b.setViewportSize({width:1408,height:768});
  step='connect host';await h.join(a, 'Reference host');
  step='connect guest';await h.join(b, 'Reference guest');
  step='participant counts';
  await count(a, 2); await count(b, 2);
  const geometry=await a.evaluate(()=>({header:document.querySelector('.room-header').getBoundingClientRect().height,sidebar:document.querySelector('.live-meeting-panel').getBoundingClientRect().width,dock:document.querySelector('.room-dock').getBoundingClientRect().height,tileTop:document.querySelector('.live-participant-tile').getBoundingClientRect().top}));
  assert.deepEqual(geometry,{header:60,sidebar:330,dock:72,tileTop:76});
  await expect(a.locator('.live-toolbar-tools>button').first().locator('span')).toBeVisible();
  step='change light and dark theme';
  await expect(a.getByRole('button',{name:'Light',exact:true})).toHaveAttribute('aria-pressed','true');
  await a.getByRole('button',{name:'Dark',exact:true}).click();
  await expect(a.locator('.call-reference')).toHaveClass(/call-theme-dark/);
  await a.getByRole('button',{name:'Light',exact:true}).click();
  step='close guest sidebar';
  if(await panel(b).isVisible())await panel(b).getByRole('button',{name:'Close meeting panel'}).click();
  step = 'Chat and People sidebar uses real participant state and messages';
  await openPanel(a, 'Participants');
  step='switch sidebar to chat';
  await panel(a).getByRole('button', {name: 'Show chat', exact: true}).click();
  await expect(a.getByRole('complementary', {name: 'In-meeting chat', exact: true})).toBeVisible();
  step='send real chat';
  const text = 'Reference check: <b>plain text</b>, no saved meeting content.';
  await panel(a).getByLabel('Message everyone', {exact: true}).fill(text);
  await panel(a).getByRole('button', {name: 'Send message', exact: true}).click();
  step='unread chat count';
  await expect(b.getByRole('button', {name: 'Chat (1 unread)', exact: true})).toBeVisible();
  await openPanel(b, 'Chat (1 unread)');
  await expect(panel(b).getByRole('log')).toContainText(text);
  assert.equal(await panel(b).locator('.live-chat-message p b').count(), 0);
  await b.screenshot({path: 'artifacts/qa/meeting-reference-chat-desktop.png'});
  await panel(a).getByRole('button', {name: 'Show people', exact: true}).click();
  await expect(panel(a).locator('.live-people-list')).toContainText('Reference guest');
  await panel(a).getByRole('button', {name: 'Close meeting panel'}).click();
  step='camera and microphone publish with the reference controls';
  await a.getByRole('button',{name:'Enable camera',exact:true}).click();
  await expect(b.locator('.live-participant-tile[data-local="false"] video')).toBeVisible();
  await expect.poll(()=>b.locator('.live-participant-tile[data-local="false"] video').evaluate(v=>v.videoWidth),{timeout:20000}).toBeGreaterThan(0);
  await a.getByRole('button',{name:'Enable microphone',exact:true}).click();
  await expect.poll(async()=>(await stats(b)).audioPackets,{timeout:20000}).toBeGreaterThan(0);
  await a.getByRole('button',{name:'Mute microphone',exact:true}).click();
  await a.getByRole('button',{name:'Turn camera off',exact:true}).click();
  step = 'circular sharing control captures a real tab and remote browser decodes it';
  const presentation = await host.context.newPage(); await presentation.goto(h.origin + '/test-presentation');
  await a.bringToFront(); await a.getByRole('button', {name: 'Share screen', exact: true}).click();
  await expect(a.getByRole('button', {name: 'Stop sharing', exact: true})).toBeVisible({timeout: 20000});
  await expect(b.locator('.live-presentation-tile video')).toBeVisible({timeout: 20000});
  await expect.poll(() => b.locator('.live-presentation-tile video').evaluate(video => video.videoWidth), {timeout: 20000}).toBeGreaterThan(0);
  await expect.poll(() => b.locator('.live-presentation-tile video').evaluate(video => {
    const canvas = document.createElement('canvas'); canvas.width = 10; canvas.height = 10;
    const ctx = canvas.getContext('2d'); ctx.drawImage(video, 0, 0, 10, 10);
    const pixel = ctx.getImageData(1, 1, 1, 1).data;
    return pixel[2] > 150 && pixel[0] < 100;
  }), {timeout: 20000}).toBe(true);
  report.realNativeScreenCapture = true;
  await a.getByRole('button', {name: 'Stop sharing', exact: true}).click();
  await expect(b.locator('[data-layout="grid"]')).toBeVisible(); await presentation.close();
  step = 'raise/lower hand and existing device settings remain available';
  await a.getByRole('button', {name: 'Raise hand', exact: true}).click();
  await expect(a.getByRole('button', {name: 'Lower hand', exact: true})).toBeVisible();
  await a.getByRole('button', {name: 'Lower hand', exact: true}).click();
  await openPanel(a, 'Settings'); await expect(a.locator('#live-videoinput')).toBeVisible();
  await expect(a.locator('#live-audioinput')).toBeVisible();
  await a.keyboard.press('Escape');
  step='mobile call controls and sidebar';
  await b.setViewportSize({width:390,height:844});
  await panel(b).getByRole('button',{name:'Close meeting panel'}).click();
  await expect(b.getByRole('button',{name:'More options',exact:true})).toBeVisible();
  await openPanel(b,'Settings');
  await expect(b.getByRole('dialog',{name:'Audio & video settings'})).toBeVisible();
  await b.keyboard.press('Escape');
  assert.ok(await b.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await b.screenshot({path:'artifacts/qa/light-call-mobile.png'});
  step='leave meeting';
  await a.getByRole('button', {name: 'Leave Meeting', exact: true}).click();
  await count(b, 1);
  assert.deepEqual(h.errors, []);
  report.passed = true;
  console.log('PASS Reference meeting: two real local browsers, Chat/People navigation, real chat/unread/plaintext, native screen share with remote pixels, hands, device settings and leave. Fixture identities; no physical-device test.');
} catch(error) {
  report.failedAt = step;
  report.assertion=String(error.message);
  await debugPage?.screenshot({path:'artifacts/qa/light-call-failure.png'}).catch(()=>{});
  process.exitCode = 1;
  console.error('FAIL Reference meeting check at: ' + step);
} finally {
  await fs.writeFile('artifacts/qa/meeting-reference-results.json', JSON.stringify(report, null, 2));
  await h.close();
}

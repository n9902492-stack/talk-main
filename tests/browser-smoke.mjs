import { localChrome } from '../scripts/browser-options.mjs';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts/qa', { recursive: true });
const browser = await chromium.launch({ ...localChrome(), headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['camera', 'microphone'] });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = 'http://localhost:3001';
const check = (name) => console.log(`PASS ${name}`);
try {
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { level: 1 }).waitFor();
  await page.locator('#feature-tabs button').first().waitFor();
  assert.match(await page.locator('h1').innerText(), /Run online meetings and webinars/);
  assert.equal(await page.locator('.skin-header').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(250, 238, 231)');
  assert.equal(await page.locator('.skin-footer').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(250, 238, 231)');
  assert.equal(await page.locator('#hero').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(255, 255, 255)');
  assert.equal(await page.locator('#meeting-showcase').count(), 0);
  assert.equal(await page.locator('#hero-control-dock button').filter({ has: page.locator('.material-symbols-outlined', { hasText: /^(mic|mic_off|videocam|videocam_off)$/ }) }).count(), 0);
  await page.screenshot({ path: 'artifacts/qa/landing-desktop.png', fullPage: true });
  for (const label of ['Bookings', 'Meetings', 'Webinars', 'Agendas', 'Transcripts', 'Cloud Storage']) {
    await page.getByRole('tab', { name: label, exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: label, exact: true }).getAttribute('aria-selected'), 'true');
    assert.ok(await page.locator('#tour-panel').isVisible());
  }
  check('Stitch landing, skin header/footer, and all six feature tabs');
  await page.getByRole('button', { name: 'Features', exact: true }).click();
  await page.locator('#menu-Features').getByRole('link', { name: 'Webinars', exact: true }).click();
  await page.waitForURL('**/webinars');
  assert.equal(await page.locator('.webinar-banner, .event-meta').count(), 0);
  for (const expected of ['Savian Boroanca', 'Jarrett Pflieger', 'Alex Gavril', 'Carla Kargaard']) {
    await page.getByRole('button', { name: 'Next speaker' }).click();
    assert.equal(await page.locator('.speaker-copy h3').innerText(), expected);
  }
  await page.screenshot({ path: 'artifacts/qa/webinar-desktop.png', fullPage: true });
  check('Webinar navigation and speaker carousel');
  await page.locator('.event-access').getByRole('link', { name: 'Test audio & video' }).click();
  await page.waitForURL('**/device-test');
  await page.getByRole('button', { name: 'Enable camera & microphone', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.camera-preview video')?.srcObject?.getTracks().length === 2);
  await page.getByRole('button', { name: 'Mute microphone', exact: true }).click();
  assert.equal(await page.locator('.camera-preview video').evaluate(video => video.srcObject.getAudioTracks()[0].enabled), false);
  await page.getByRole('button', { name: 'Enable microphone', exact: true }).click();
  await page.getByRole('button', { name: 'Turn camera off', exact: true }).click();
  await page.getByRole('heading', { name: 'Your camera is off' }).waitFor();
  await page.getByRole('button', { name: 'Enable camera', exact: true }).click();
  await page.getByRole('button', { name: 'Play test sound', exact: true }).click();
  await page.getByRole('button', { name: 'I can hear the sound' }).click();
  await page.getByRole('button', { name: 'Record a 5-second mic test', exact: true }).click();
  await page.waitForTimeout(1000);
  await page.getByRole('button', { name: 'Stop recording', exact: true }).click();
  await page.locator('audio').waitFor();
  assert.ok((await page.locator('audio').getAttribute('src')).startsWith('blob:'));
  await page.screenshot({ path: 'artifacts/qa/device-test-desktop.png', fullPage: true });
  const tracks = await page.locator('video').evaluateHandle(video => video.srcObject.getTracks());
  await page.getByRole('link', { name: 'Join session', exact: true }).click();
  await page.waitForURL('**/meeting');
  assert.equal(await tracks.evaluate(value => value.every(track => track.readyState === 'ended')), true);
  check('Camera/mic setup, mute, camera toggle, speaker test, mic recording, and track cleanup');
  await page.getByRole('button', { name: 'Next agenda item' }).click();
  assert.match(await page.locator('.agenda-card.active h3').innerText(), /Creating Engaging Content/);
  await page.getByRole('button', { name: 'Chat', exact: true }).click();
  await page.getByRole('textbox', { name: 'Chat message' }).fill('Hello from the local preview');
  await page.getByRole('button', { name: 'Send message' }).click();
  assert.ok(await page.getByText('Hello from the local preview', { exact: true }).isVisible());
  await page.getByRole('button', { name: 'Q&A', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your question' }).fill('How do the agenda tools work?');
  await page.getByRole('button', { name: 'Send question' }).click();
  await page.getByRole('button', { name: '0 Upvote' }).click();
  assert.ok(await page.getByRole('button', { name: '1 Voted' }).isVisible());
  await page.getByRole('button', { name: 'Close side panel' }).click();
  await page.getByRole('button', { name: 'Whiteboard', exact: true }).click();
  const bounds = await page.locator('.drawing-layer').boundingBox();
  await page.mouse.move(bounds.x + 70, bounds.y + 120); await page.mouse.down(); await page.mouse.move(bounds.x + 150, bounds.y + 150); await page.mouse.up();
  assert.equal(await page.locator('.drawing-layer path').count(), 1);
  await page.getByRole('button', { name: 'Undo last stroke' }).click();
  assert.equal(await page.locator('.drawing-layer path').count(), 0);
  await page.getByRole('button', { name: 'Reactions', exact: true }).click();
  await page.getByRole('button', { name: 'React 👏', exact: true }).click();
  assert.ok(await page.locator('.floating-reaction').isVisible());
  await page.screenshot({ path: 'artifacts/qa/meeting-desktop.png', fullPage: true });
  check('Meeting agenda, chat, Q&A voting, whiteboard drawing/undo, and reactions');
  await page.goto(base + '/bookings', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Full name', { exact: true }).fill('Local Booking');
  await page.getByLabel('Email', { exact: true }).fill('booking@example.com');
  await page.getByRole('button', { name: 'Schedule session' }).click();
  await page.locator('.booking-success').waitFor();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Add to calendar' }).click();
  assert.equal((await download).suggestedFilename(), 'talk-session.ics');
  check('Booking validation, local confirmation, and calendar download');
  const response = await page.request.get(base + '/reference/session-recording.mp4', { headers: { Range: 'bytes=1000000-1001023' } });
  assert.equal(response.status(), 206); assert.equal((await response.body()).length, 1024);
  check('Original MP4 supports byte ranges for seeking');
  for (const [url, name] of [['/', 'landing'], ['/webinars', 'webinar'], ['/device-test', 'device-test'], ['/meeting', 'meeting']]) {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + url, { waitUntil: 'domcontentloaded' });
    await page.locator(url === '/' ? '#feature-tabs button' : url === '/webinars' ? '.speakers-section' : url === '/device-test' ? '.camera-preview' : '.room-stage').first().waitFor();
    await page.screenshot({ path: `artifacts/qa/${name}-mobile.png`, fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true, `${name} has mobile horizontal overflow`);
  }
  assert.deepEqual(errors, []);
  check('Desktop/mobile rendering and no uncaught browser exceptions');
} finally { await browser.close(); }

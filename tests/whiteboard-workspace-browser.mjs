import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { localChrome } from '../scripts/browser-options.mjs';
import { schedulingHarness } from './helpers/scheduling.mjs';

process.env.WHITEBOARD_CLOUD_AI_ENABLED = 'false';
process.env.WHITEBOARD_CLOUD_AI_OPERATOR_APPROVED = 'false';
const build = process.env.TALK_TEST_FRONTEND_BUILD || 'artifacts/qa/whiteboard-workspace-build';
const h = await schedulingHarness({ frontendBuild: build, transportEnabled: false, whiteboardIntelligence: { provider: { configured: false, reason: 'No inference in browser tests.' } } });
let browser, step = 'fixtures';
const errors = [];
try {
  const host = await h.account('WhiteboardHost'), other = await h.account('OtherBoardHost');
  const created = await host.request('meetings', { title: 'Product Ideas', approvalRequired: true });
  assert.equal(created.status, 201); const id = created.body.meeting.id;
  assert.equal((await host.request('meetings', { title: 'Design Review', approvalRequired: true })).status, 201);
  const privateMeeting = await other.request('meetings', { title: 'Other private board', approvalRequired: true });
  browser = await chromium.launch({ ...localChrome(), headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
  const requests = [];
  await context.route('**/*', route => {
    const url = new URL(route.request().url()); requests.push(url.pathname);
    return url.origin === h.origin ? route.continue() : route.abort();
  });
  await context.addCookies([...host.jar].map(([name, value]) => ({ name, value, url: h.origin + '/api/auth', httpOnly: true, sameSite: 'Lax' })));
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  step = 'sidebar and library';
  await page.goto(h.origin + '/dashboard');
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Whiteboard', exact: true }).click();
  await expect(page).toHaveURL(h.origin + '/whiteboard');
  await expect(page.getByRole('heading', { name: 'Whiteboard', exact: true })).toBeVisible();
  await expect(page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Whiteboard', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('list', { name: 'Meeting whiteboards' }).getByRole('listitem')).toHaveCount(2);
  await expect(page.getByText('Other private board', { exact: true })).toHaveCount(0);
  await page.getByRole('searchbox', { name: 'Search whiteboards by meeting or host' }).fill('product');
  await expect(page.getByRole('listitem')).toHaveCount(1);
  await page.getByRole('searchbox').fill('');
  await page.screenshot({ path: 'artifacts/qa/whiteboard-workspace-library.png' });
  step = 'open editor and save real canvas note';
  await page.getByRole('link', { name: 'Open whiteboard for Product Ideas', exact: true }).click();
  await expect(page).toHaveURL(h.origin + '/whiteboard?meeting=' + id);
  await page.getByRole('button', { name: 'Open meeting whiteboard', exact: true }).click();
  const board = page.getByRole('region', { name: 'Meeting whiteboard', exact: true });
  await expect(board).toHaveAttribute('data-elements', '0');
  for (const name of ['Pen', 'Highlighter', 'Eraser', 'Text', 'Rectangle', 'Rounded rectangle', 'Ellipse', 'Line', 'Arrow', 'Sticky note', 'Select', 'Pan', 'Upload image', 'Whiteboard permissions and snapshots']) await expect(board.getByRole('button', { name, exact: true })).toBeEnabled();
  await board.getByRole('button', { name: 'Sticky note', exact: true }).click();
  const box = await board.locator('.wb-canvas').boundingBox();
  await page.mouse.click(box.x + 100, box.y + 120);
  await page.locator('#wb-text-content').fill('Synthetic workspace idea');
  await page.getByRole('button', { name: 'Save text', exact: true }).click();
  await expect(board).toHaveAttribute('data-elements', '1');
  assert.match(h.raw.prepare('SELECT state_json FROM talk_whiteboards WHERE meeting_id=?').get(id).state_json, /Synthetic workspace idea/);
  await board.getByRole('button', { name: 'Undo my last change', exact: true }).click();
  await expect(board).toHaveAttribute('data-elements', '0');
  await board.getByRole('button', { name: 'Redo my last change', exact: true }).click();
  await expect(board).toHaveAttribute('data-elements', '1');
  step = 'existing assistant with consent and template preview';
  const assistant = page.getByRole('complementary', { name: 'Whiteboard AI Assistant' });
  if (!await assistant.isVisible()) await board.getByRole('button', { name: 'AI Assistant', exact: true }).click();
  await assistant.getByLabel('Canvas assistant prompt').fill('Fictional team planning');
  await assistant.getByLabel('Use the displayed prompt or text selection for this proposal.').check();
  await assistant.getByRole('button', { name: 'Create editable template', exact: true }).click();
  await expect(assistant.getByRole('img', { name: 'Editable diagram proposal preview' })).toBeVisible({ timeout: 15000 });
  await expect(board).toHaveAttribute('data-elements', '1');
  await assistant.getByRole('button', { name: 'Insert into Canvas', exact: true }).click();
  await expect.poll(async () => Number(await board.getAttribute('data-elements'))).toBeGreaterThan(10);
  const savedCount = await board.getAttribute('data-elements');
  const capabilities = await host.request(`meetings/${id}/whiteboard/ai/capabilities`);
  assert.equal(capabilities.body.cloud.enabled, false);
  await page.screenshot({ path: 'artifacts/qa/whiteboard-workspace-editor.png' });
  step = 'reload, export and existing details share the same board';
  await page.reload(); await expect(board).toHaveAttribute('data-elements', savedCount);
  assert.equal((await host.request(`meetings/${id}/whiteboard/export/svg`)).status, 200);
  await board.getByRole('button', { name: 'Back to whiteboards', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your meeting whiteboards', exact: true })).toBeVisible();
  await page.goto(h.origin + `/meeting-history/${id}?tab=whiteboard`);
  await expect(board).toHaveAttribute('data-elements', savedCount);
  step = 'cross-user and signed-out isolation';
  assert.equal((await other.request(`meetings/${id}/whiteboard`)).status, 404);
  await page.goto(h.origin + '/whiteboard?meeting=' + privateMeeting.body.meeting.id);
  await expect(page.getByRole('heading', { name: 'Whiteboard unavailable', exact: true })).toBeVisible();
  await expect(board).toHaveCount(0);
  const outsider = await browser.newContext(); const outsidePage = await outsider.newPage();
  await outsider.route('**/*', route => new URL(route.request().url()).origin === h.origin ? route.continue() : route.abort());
  await outsidePage.goto(h.origin + '/whiteboard'); await expect(outsidePage).toHaveURL(/\/sign-in$/);
  await outsider.close();
  step = 'mobile and collapsed sidebar';
  await page.goto(h.origin + '/whiteboard');
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Whiteboard', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Whiteboard', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Workspace navigation' })).not.toBeVisible();
  await page.getByRole('link', { name: 'Open whiteboard for Product Ideas', exact: true }).click();
  await expect(board).toHaveAttribute('data-elements', savedCount);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/qa/whiteboard-workspace-mobile.png' });
  assert.equal(requests.some(url => /\/join$|\/ai\/cloud\/(?:approve|send)$/.test(url)), false);
  assert.equal(h.outbox.length, 0); assert.equal(h.codes.length, 0);
  assert.deepEqual(errors, []);
  await fs.writeFile('artifacts/qa/whiteboard-workspace-results.json', JSON.stringify({ passed: true, sidebar: true, actualDatabaseSave: true, undoRedo: true, consentTemplatePreviewInsert: true, reloadAndMeetingDetailsPersistence: true, privateExport: true, authorization: true, mobile: true, noInferenceOrEmails: true }, null, 2));
  console.log('PASS: Whiteboard sidebar/library, real saved objects, full editor tools, undo/redo, consented local templates, reload/details persistence, exports, private access and mobile. No video join, external inference or email.');
} catch (error) {
  console.error(`FAIL whiteboard workspace at ${step}: ${error.message}`); process.exitCode = 1;
} finally {
  await browser?.close(); await h.close();
}

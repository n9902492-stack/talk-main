import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { chromium, expect } from '@playwright/test';
import { schedulingHarness } from './helpers/scheduling.mjs';
import { localChrome } from '../scripts/browser-options.mjs';

let h, browser, page, step = 'fixture';
try {
  h = await schedulingHarness({ frontendBuild: process.env.TALK_TEST_FRONTEND_BUILD || 'artifacts/qa/booking-calendar-build', transportEnabled: false });
  const host = await h.account('CalendarHost');
  assert.equal((await host.request('scheduling/profile', { slug: 'calendar-host', timezone: 'UTC', settings: { notice: 0, bufferAfter: 10 }, windows: Array.from({ length: 7 }, (_, weekday) => ({ weekday, start: 540, end: 1020 })) })).status, 200);
  const event = (await host.request('scheduling/events', { slug: 'design', title: 'Team Design Review', duration: 30, capacity: 1 })).body.event;
  const day = Math.floor((h.now() + 2 * 86400000) / 86400000) * 86400000, date = new Date(day).toISOString().slice(0, 10);
  async function book(start, name) {
    const token = (await host.request('scheduling/form')).body.formToken;
    const result = await host.request(`scheduling/events/${event.id}/book`, { start, name, email: name.toLowerCase() + '@example.test', timezone: 'UTC', credential: randomBytes(32).toString('base64url'), answers: {} }, { 'X-Scheduling-Token': token });
    assert.equal(result.status, 201); return result.body.booking;
  }
  const a = await book(day + 10 * 3600000, 'FictionalAlice');
  const b = await book(day + 11 * 3600000, 'FictionalBob');
  const cancelled = await book(day + 15 * 3600000, 'FictionalCara');
  assert.equal((await host.request(`scheduling/host-booking/${cancelled.id}/change`, { action: 'cancel', version: 1 })).status, 200);
  browser = await chromium.launch({ ...localChrome(), headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const requests = [], errors = [];
  await context.route('**/*', route => { const url = new URL(route.request().url()); requests.push({ path: url.pathname, method: route.request().method() }); return url.origin === h.origin ? route.continue() : route.abort(); });
  await context.addCookies([...host.jar].map(([name, value]) => ({ name, value, url: h.origin + '/api/auth', httpOnly: true, sameSite: 'Lax' })));
  page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  step = 'calendar launcher and lazy loading';
  await page.goto(h.origin + '/bookings');
  const header = page.locator('.scheduler-page-header');
  const launcher = header.getByRole('button', { name: 'Booking calendar', exact: true });
  const dialog = page.getByRole('dialog', { name: 'Booking calendar', exact: true, includeHidden: true });
  const calendar = page.getByRole('region', { name: 'Booking calendar', exact: true });
  const slotRequests = () => requests.filter(request => request.path.includes('/scheduling/events/') && request.path.endsWith('/slots'));
  await expect(launcher).toBeVisible();
  await expect(launcher).toBeEnabled();
  await expect(launcher).toHaveAttribute('aria-haspopup', 'dialog');
  await expect(launcher).toHaveAttribute('aria-controls', 'booking-calendar-dialog');
  await expect(launcher).toHaveAttribute('aria-expanded', 'false');
  await expect(page.locator('#booking-' + a.id)).toBeVisible();
  await expect(dialog).not.toBeVisible();
  await expect(calendar).toHaveCount(0);
  assert.equal(slotRequests().length, 0, 'Availability must only be requested after opening the calendar');
  const headerBox = await header.boundingBox(), launcherBox = await launcher.boundingBox(), titleBox = await header.getByRole('heading', { name: 'Bookings', exact: true }).boundingBox();
  assert.ok(headerBox && launcherBox && titleBox);
  assert.ok(launcherBox.x >= titleBox.x + titleBox.width, 'Calendar launcher must sit to the right of the Bookings heading');
  assert.ok(headerBox.x + headerBox.width - launcherBox.x - launcherBox.width <= 12, 'Calendar launcher must align with the right of the page header');
  await page.screenshot({ path: 'artifacts/qa/booking-calendar-launcher-desktop.png' });
  async function openCalendar() {
    await launcher.click();
    await expect(dialog).toBeVisible();
    await expect(launcher).toHaveAttribute('aria-expanded', 'true');
    await expect(calendar).toBeVisible();
    assert.equal(await dialog.evaluate(element => element.matches(':modal')), true);
    assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true, 'Opening the calendar must move focus into the dialog');
  }
  async function expectCalendarClosed() {
    await expect(dialog).not.toBeVisible();
    await expect(calendar).toHaveCount(0);
    await expect(launcher).toHaveAttribute('aria-expanded', 'false');
    await expect(launcher).toBeFocused();
  }
  step = 'modal dismissal and focus restoration';
  await openCalendar();
  await expect(calendar.locator('.scheduling-calendar-block.is-available').first()).toBeVisible();
  assert.ok(slotRequests().length > 0, 'Opening the calendar must load server availability');
  await page.keyboard.press('Escape');
  await expectCalendarClosed();
  await openCalendar();
  await calendar.getByRole('button', { name: 'Close booking calendar', exact: true }).click();
  await expectCalendarClosed();
  await openCalendar();
  const dialogBox = await dialog.boundingBox();
  assert.ok(dialogBox && (dialogBox.x > 4 || dialogBox.y > 4), 'The dialog must leave a backdrop available to dismiss it');
  await page.mouse.click(2, 2);
  await expectCalendarClosed();
  step = 'real calendar appointments and availability';
  await openCalendar();
  await calendar.getByLabel('Calendar starting date', { exact: true }).fill(date);
  await expect(calendar).toHaveAttribute('aria-busy', 'false');
  await expect(calendar.locator('.is-booking')).toHaveCount(2);
  await expect(calendar.locator('.scheduling-calendar-block.is-available').first()).toBeVisible();
  const available = (await host.request(`scheduling/events/${event.id}/slots?from=${day}&to=${day + 3 * 86400000}&timezone=UTC`)).body.slots;
  assert.ok(!available.some(slot => slot.start < a.end && slot.end > a.start));
  await calendar.locator('.scheduling-calendar-block.is-available').first().click();
  const selection = calendar.getByRole('region', { name: 'Calendar selection', exact: true });
  await expect(selection.getByRole('heading', { name: 'Available start times', exact: true })).toBeVisible();
  assert.ok(await selection.locator('li').count() > 0);
  await expect(selection.getByRole('link', { name: 'Open booking page', exact: true })).toHaveAttribute('href', '/booking/calendar-host/design');
  await calendar.getByRole('button', { name: 'Close calendar selection', exact: true }).click();
  await calendar.locator('.is-booking').first().click();
  await expect(selection).toContainText('FictionalAlice');
  await selection.getByRole('link', { name: 'Manage booking, reschedule or cancel', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(launcher).toHaveAttribute('aria-expanded', 'false');
  await expect(calendar).toHaveCount(0);
  await expect(page.locator('#booking-' + a.id)).toBeInViewport();
  await expect(page.locator('#booking-' + a.id)).toBeFocused();
  assert.equal(new URL(page.url()).hash, '#booking-' + a.id);
  await openCalendar();
  await calendar.getByLabel('Calendar starting date', { exact: true }).fill(date);
  await expect(calendar).toHaveAttribute('aria-busy', 'false');
  await expect(selection).toHaveCount(0);
  await page.screenshot({ path: 'artifacts/qa/booking-calendar-desktop.png' });
  step = 'rescheduling and cancellation refresh';
  assert.equal((await host.request(`scheduling/host-booking/${b.id}/change`, { action: 'reschedule', version: 1, start: day + 12 * 3600000, newCredential: randomBytes(32).toString('base64url') })).status, 200);
  await calendar.getByRole('button', { name: 'Refresh calendar', exact: true }).click();
  await expect(calendar.getByRole('button', { name: /FictionalBob, 12:00/ })).toBeVisible();
  assert.equal((await host.request(`scheduling/host-booking/${a.id}/change`, { action: 'cancel', version: 1 })).status, 200);
  await calendar.getByRole('button', { name: 'Refresh calendar', exact: true }).click();
  await expect(calendar.locator('.is-booking')).toHaveCount(1);
  step = 'view controls and mobile';
  await calendar.getByLabel('Calendar view', { exact: true }).selectOption('7');
  await expect(calendar.locator('.scheduling-calendar-day-heading')).toHaveCount(7);
  await calendar.getByRole('button', { name: 'Next calendar dates', exact: true }).click();
  await expect(calendar.getByLabel('Calendar starting date', { exact: true })).not.toHaveValue(date);
  await calendar.getByRole('button', { name: 'Previous calendar dates', exact: true }).click();
  await expect(calendar.getByLabel('Calendar starting date', { exact: true })).toHaveValue(date);
  await calendar.getByLabel('Calendar view', { exact: true }).selectOption('3');
  await calendar.getByRole('button', { name: 'Close booking calendar', exact: true }).click();
  await expectCalendarClosed();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(launcher).toBeInViewport();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await openCalendar();
  await expect(calendar.getByLabel('Calendar starting date', { exact: true })).not.toHaveValue(date);
  await calendar.getByLabel('Calendar starting date', { exact: true }).fill(date);
  await expect(calendar).toHaveAttribute('aria-busy', 'false');
  const mobileDialogBox = await dialog.boundingBox();
  assert.ok(mobileDialogBox && mobileDialogBox.x >= 0 && mobileDialogBox.x + mobileDialogBox.width <= 390 && mobileDialogBox.y >= 0 && mobileDialogBox.y + mobileDialogBox.height <= 844, 'The mobile calendar dialog must fit inside the viewport');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const scroller = calendar.getByRole('region', { name: 'Scrollable booking calendar', exact: true });
  assert.equal(await scroller.evaluate(element => element.scrollWidth > element.clientWidth), true);
  await scroller.evaluate(element => { element.scrollLeft = element.scrollWidth; });
  await page.screenshot({ path: 'artifacts/qa/booking-calendar-mobile.png' });
  step = 'past range and no side effects';
  await calendar.getByLabel('Calendar starting date', { exact: true }).fill('2020-01-01');
  await expect(calendar.locator('.scheduling-calendar-block.is-available')).toHaveCount(0);
  assert.equal(requests.some(request => request.method !== 'GET'), false, 'Calendar must never reserve, reschedule or email merely by clicking');
  assert.equal(h.outbox.length, 0); assert.equal(h.codes.length, 0); assert.deepEqual(errors, []);
  await calendar.getByRole('button', { name: 'Close booking calendar', exact: true }).click();
  await expectCalendarClosed();
  await fs.writeFile('artifacts/qa/booking-calendar-results.json', JSON.stringify({ passed: true, launcher: true, modalDismissal: true, lazyLoading: true, focus: true, headerLauncher: true, lazyAvailability: true, modalDismissalAndFocus: true, actualBookings: true, serverAvailability: true, details: true, manageBookingFocus: true, rescheduleAndCancellationRefresh: true, dateNavigation: true, mobile: true, mobileReopen: true, readOnlyCalendar: true, externalEmails: 0 }, null, 2));
  console.log('PASS: Booking calendar opens from the right-hand header launcher, loads availability on demand, dismisses with Escape/close/backdrop and restores focus. Real bookings, management links, refreshed reschedules/cancellations, date/view navigation and mobile reopening/scrolling work. Read-only interaction; no external emails or AI.');
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  await fs.writeFile('artifacts/qa/booking-calendar-results.json', JSON.stringify({ passed: false, step, error: message }, null, 2));
  if (page) { await page.screenshot({ path: 'artifacts/qa/booking-calendar-failure.png' }).catch(() => {}); await fs.writeFile('artifacts/qa/booking-calendar-failure.txt', await page.locator('body').innerText()).catch(() => {}); }
  console.error(`FAIL booking calendar at ${step}: ${message}`); process.exitCode = 1;
}
finally { await browser?.close(); await h?.close(); }
